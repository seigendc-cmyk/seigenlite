const READ = (f) => fs.readFileSync(path.join(MIG, f), 'utf8').replace(/\r\n/g, '\n');
function body(file, startText, endText) {
  const src = READ(file);
  const start = src.indexOf(startText);
  const end = src.indexOf(endText, start) + endText.length;
  if (start < 0 || end < start + endText.length) throw new Error(startText + ' not found in ' + file);
  if (src.indexOf(startText, end) >= 0) throw new Error(startText + ' twice in ' + file);
  return src.slice(start, end);
}
function swap(text, from, to) {
  if (text.split(from).length !== 2) throw new Error('expected exactly one: ' + from.slice(0, 80));
  return text.replace(from, () => to);
}

