-- =====================================================================
-- A joined device's Admin passcode is set by the main branch (owner,
-- 2026-10-13: "the main branch Admin sets the new device's Admin passcode";
-- also for extra tills of the main branch; 6 characters; "refuse join codes
-- from an older main build, with the message 'Update the main branch till
-- first'"). Applied live only after the owner has seen this file and said
-- "apply".
-- Design: docs/multi-terminal/admin-passcode-on-join-design.md
-- Rollback: supabase/rollbacks/20261023120000_admin_passcode_from_main.rollback.sql
-- Tested in PGlite: supabase/tests/admin-passcode-from-main-test.js
-- Generated by tools/db/gen-20261023-migration.js (current bodies + marked lines).
--
-- Only a CHECK VALUE travels, never the passcode: the main till computes
-- PBKDF2-HMAC-SHA-256(passcode, 16-byte salt, rounds) itself (app v21,
-- src/passcode-check.js); seiGEN stores the salt, the result and the rounds,
-- and hands them to that one device: in the join answer, or once in a
-- check-in answer. The device compares typed passcodes against it, offline.
--
-- Changes:
--   cl_branch_join_codes        + admin_salt, admin_check, admin_rounds
--   cl_terminal_admin_seeds     new: one pending check value per till
--   cl_admin_seed_ok            new (internal): is it a well-formed check value?
--   cl_terminal_join_json       new (internal): the terminal's JSON + its code's check value
--   cl_branch_issue_join_code   + p_admin_salt/check/rounds, REQUIRED
--                               (an older main build is told "Update the main branch till first")
--   cl_terminal_join            + p_app_build: an app before v21 is told to update first;
--                               a code without a check value: ADMIN_SEED_MISSING;
--                               the answer carries admin_seed
--   cl_terminal_admin_set       new: a main-branch till sets another till's check value
--   cl_device_checkin           the answer carries admin_seed once (same signature)
-- Existing unused join codes have no check value, so they can't be used: the
-- main till issues a new one.
-- =====================================================================

begin;

-- 0. Preflight ----------------------------------------------------------
do $$
declare missing text;
begin
  if to_regclass('public.cl_terminal_admin_seeds') is not null
     or exists (select 1 from pg_proc where proname = 'cl_device_checkin' and prosrc like '%admin passcode seed%') then
    raise exception 'admin_passcode_from_main aborted: already there (cl_terminal_admin_seeds or the check-in seed). Nothing was changed.';
  end if;
  select string_agg(n, ', ') into missing from (
    select 'function cl_branch_issue_join_code (6 args)' n where to_regprocedure('public.cl_branch_issue_join_code(text,text,text,uuid,text,integer)') is null
    union all select 'function cl_terminal_join (10 args)' where to_regprocedure('public.cl_terminal_join(text,text,text,text,text,text,text,text,text,text)') is null
    union all select 'function cl_device_checkin (11 args)' where to_regprocedure('public.cl_device_checkin(text,text,text,text,text,text,text,text,uuid,text,integer)') is null
    union all select 'the shared stock lock in cl_device_checkin' where not exists (select 1 from pg_proc where proname = 'cl_device_checkin' and prosrc like '%shared stock lock%')
  ) x;
  if missing is not null then raise exception 'admin_passcode_from_main aborted: missing %. Nothing was changed.', missing; end if;
end $$;

-- 1. Where the check values live ------------------------------------------
alter table public.cl_branch_join_codes
  add column admin_salt   text,
  add column admin_check  text,
  add column admin_rounds integer,
  add constraint cl_branch_join_codes_admin_check_ok check (
    (admin_salt is null and admin_check is null and admin_rounds is null)
    or (admin_salt ~ '^[0-9a-f]{32}$' and admin_check ~ '^[0-9a-f]{64}$' and admin_rounds between 100000 and 2000000));

create table public.cl_terminal_admin_seeds (
  terminal_id     uuid primary key references public.cl_terminals(id),
  salt            text not null check (salt ~ '^[0-9a-f]{32}$'),
  check_value     text not null check (check_value ~ '^[0-9a-f]{64}$'),
  rounds          integer not null check (rounds between 100000 and 2000000),
  set_by_terminal uuid not null references public.cl_terminals(id),
  created_ts      timestamptz not null default now(),
  delivered_ts    timestamptz
);
comment on table public.cl_terminal_admin_seeds is 'Admin passcode from main (20261023120000): the check value (never the passcode) a main-branch till set for another till; delivered once in its check-in answer.';
alter table public.cl_terminal_admin_seeds enable row level security;
revoke all on table public.cl_terminal_admin_seeds from anon, authenticated;

-- 2. Helpers (internal) -------------------------------------------------
create function public.cl_admin_seed_ok(p_salt text, p_check text, p_rounds integer) returns boolean
language sql immutable set search_path = public as $$
  select coalesce(p_salt ~ '^[0-9a-f]{32}$' and p_check ~ '^[0-9a-f]{64}$' and p_rounds between 100000 and 2000000, false)
$$;
revoke execute on function public.cl_admin_seed_ok(text, text, integer) from public, anon, authenticated;

-- The terminal's JSON, plus its join code's check value (only for the till that used the code).
create function public.cl_terminal_join_json(p_terminal_id uuid, p_code_id uuid) returns json
language sql stable set search_path = public as $$
  select (cl_terminal_json(p_terminal_id)::jsonb || jsonb_build_object('admin_seed',
           (select jsonb_build_object('salt', c.admin_salt, 'check', c.admin_check, 'rounds', c.admin_rounds)
              from cl_branch_join_codes c
             where c.id = p_code_id and c.used_by_terminal = p_terminal_id and c.admin_check is not null)))::json
$$;
revoke execute on function public.cl_terminal_join_json(uuid, uuid) from public, anon, authenticated;

-- 3. Issuing a join code (price plans body + marked lines) ------------------
drop function public.cl_branch_issue_join_code(text, text, text, uuid, text, int);
create or replace function public.cl_branch_issue_join_code(
  p_install_id text, p_secret_phrase text, p_device_key text,
  p_branch_id uuid default null, p_new_branch_name text default null, p_valid_hours int default 24,
  p_admin_salt text default null, p_admin_check text default null, p_admin_rounds int default null)   -- admin passcode from main
returns json
language plpgsql security definer set search_path = public as $fn$
declare v cl_vendors%rowtype; me cl_terminals%rowtype; target cl_branches%rowtype; code text; exp timestamptz;
        v_max integer;   -- Price plans (20261013120000)
begin
  v := cl_install_vendor(p_install_id, p_secret_phrase, p_device_key, false);
  -- admin passcode from main: a code without the new device's Admin check value comes from an older main build
  if not cl_admin_seed_ok(p_admin_salt, p_admin_check, p_admin_rounds) then
    raise exception 'UPDATE_MAIN_FIRST: Update the main branch till first. It sets the new device''s Admin passcode when it issues the code.' using errcode = 'P0001';
  end if;
  select t.* into me from cl_terminals t join cl_branches b on b.id = t.branch_id
   where t.vendor_id = v.id and t.active and b.is_main;
  if not found then raise exception 'Only a main-branch terminal can add terminals' using errcode = 'P0001'; end if;

  if (p_branch_id is null) = (nullif(btrim(coalesce(p_new_branch_name,'')), '') is null) then
    raise exception 'Give either a branch or a new branch name';
  end if;
  -- Price plans (20261013120000): the business's plan may limit its branches (Lite: one).
  v_max := (cl_plan_version((select pl.plan_code from cl_plan_of(me.business_id, null) pl))).max_branches;
  if p_branch_id is not null then
    select * into target from cl_branches where id = p_branch_id and business_id = me.business_id;
    if not found then raise exception 'Branch not found in this business'; end if;
    if not target.is_main and not cl_plan_branch_allowed(target.id, v_max) then raise exception '%', cl_plan_branch_limit_text(v_max); end if;
  else
    select * into target from cl_branches where business_id = me.business_id and cl_branch_key(name) = cl_branch_key(p_new_branch_name);
    if found and not target.is_main and not cl_plan_branch_allowed(target.id, v_max) then raise exception '%', cl_plan_branch_limit_text(v_max); end if;
    if not found then
      if v_max is not null and (select count(*) from cl_branches cb where cb.business_id = me.business_id) >= v_max then
        raise exception '%', cl_plan_branch_limit_text(v_max);
      end if;
      insert into cl_branches (business_id, name, is_main) values (me.business_id, btrim(p_new_branch_name), false)
      returning * into target;
    end if;
  end if;

  exp := now() + make_interval(hours => greatest(1, least(coalesce(p_valid_hours, 24), 72)));
  loop
    code := cl_new_join_code();
    begin
      insert into cl_branch_join_codes (branch_id, code_hash, issued_by_terminal, expires_ts,
                                        admin_salt, admin_check, admin_rounds)                  -- admin passcode from main
      values (target.id, encode(extensions.digest(code, 'sha256'), 'hex'), me.id, exp,
              p_admin_salt, p_admin_check, p_admin_rounds);
      exit;
    exception when unique_violation then -- astronomically rare: draw again
    end;
  end loop;
  return json_build_object('code', substr(code,1,4) || '-' || substr(code,5,4),
    'branch_id', target.id, 'branch_name', target.name, 'expires_ts', exp);
end $fn$;
grant execute on function public.cl_branch_issue_join_code(text, text, text, uuid, text, int, text, text, int) to anon, authenticated;

-- 4. Joining (price plans body + marked lines) --------------------------------
drop function public.cl_terminal_join(text, text, text, text, text, text, text, text, text, text);
create or replace function public.cl_terminal_join(
  p_install_id text, p_secret_phrase text, p_device_key text, p_join_code text,
  p_label text default null, p_legacy_branch_id text default null,
  p_device_phrase text default null, p_device_code text default null, p_business_name text default null,
  p_expected_branch_name text default null, p_app_build integer default null)   -- admin passcode from main
returns json
language plpgsql security definer set search_path = public as $fn$
declare v cl_vendors%rowtype; jc cl_branch_join_codes%rowtype; br cl_branches%rowtype; biz cl_businesses%rowtype;
        t cl_terminals%rowtype; norm text := cl_norm_join_code(p_join_code);
begin
  if (select count(*) from cl_join_failures where install_id = p_install_id and ts > now() - interval '1 hour') >= 10 then
    raise exception 'JOIN_LOCKED: Too many wrong codes. Try again in an hour.' using errcode = 'P0001';
  end if;

  select * into jc from cl_branch_join_codes where code_hash = encode(extensions.digest(norm, 'sha256'), 'hex') for update;
  if not found then
    insert into cl_join_failures (install_id) values (p_install_id);
    -- the failure row must survive the exception, so return an error object
    -- instead of raising (a raise would roll the insert back)
    return json_build_object('error', 'JOIN_CODE_INVALID');
  end if;
  select * into br from cl_branches where id = jc.branch_id;
  select * into biz from cl_businesses where id = br.business_id;

  if extensions.crypt(cl_norm_phrase(p_secret_phrase), biz.secret_phrase_hash) <> biz.secret_phrase_hash then
    insert into cl_join_failures (install_id) values (p_install_id);
    return json_build_object('error', 'PHRASE_MISMATCH');
  end if;

  -- Already a terminal? A retried join answers the same; nothing is created.
  select * into t from cl_terminals where install_id = p_install_id;
  if found then
    if not t.active then return json_build_object('error', 'TERMINAL_INACTIVE'); end if;   -- Phase 2
    v := cl_install_vendor(p_install_id, coalesce(nullif(p_device_phrase, ''), p_secret_phrase), p_device_key, false);
    if t.branch_id = br.id then return cl_terminal_join_json(t.id, jc.id); end if;   -- admin passcode from main
    return json_build_object('error', 'ALREADY_JOINED', 'branch_id', t.branch_id);
  end if;
  -- Every refusal comes before anything is written for this install.
  if jc.used_by_terminal is not null then return json_build_object('error', 'JOIN_CODE_USED'); end if;
  if jc.expires_ts < now() then return json_build_object('error', 'JOIN_CODE_EXPIRED'); end if;
  -- admin passcode from main: an app before v21 would ignore the Admin passcode (and let anyone set one)
  if coalesce(p_app_build, 0) < 21 then
    raise exception 'APP_UPDATE_NEEDED: Update this app first, then join again. Your join code is still valid.' using errcode = 'P0001';
  end if;
  if jc.admin_check is null then return json_build_object('error', 'ADMIN_SEED_MISSING'); end if;   -- a code from an older main build
  -- An existing device's branch name is locked (DN keys carry it), so it
  -- may only join a branch of the same name.
  if nullif(btrim(coalesce(p_expected_branch_name,'')), '') is not null
     and cl_branch_key(p_expected_branch_name) <> cl_branch_key(br.name) then
    return json_build_object('error', 'BRANCH_NAME_MISMATCH', 'branch_name', br.name);
  end if;
  if exists (select 1 from cl_vendors where install_id = p_install_id and business_id is not null and business_id <> biz.id) then
    return json_build_object('error', 'OTHER_BUSINESS');
  end if;
  -- Price plans (20261013120000): a branch beyond the plan's limit (Lite: one) takes no tills.
  if not br.is_main and not cl_plan_branch_allowed(br.id, (cl_plan_version((select pl.plan_code from cl_plan_of(biz.id, null) pl))).max_branches) then
    raise exception '%', cl_plan_branch_limit_text((cl_plan_version((select pl.plan_code from cl_plan_of(biz.id, null) pl))).max_branches);
  end if;

  v := cl_install_vendor(p_install_id, coalesce(nullif(p_device_phrase, ''), p_secret_phrase), p_device_key, true,
                         coalesce(p_business_name, biz.name), p_device_code);

  perform 1 from cl_branches where id = br.id for update;            -- serialise till numbering
  insert into cl_terminals (business_id, branch_id, vendor_id, install_id, till_code, label, last_seen_ts)
  values (biz.id, br.id, v.id, v.install_id, cl_next_till_code(br.id), nullif(btrim(coalesce(p_label,'')), ''), now())
  returning * into t;
  update cl_branch_join_codes set used_by_terminal = t.id, used_ts = now() where id = jc.id;
  update cl_vendors set business_id = biz.id where id = v.id;
  if not br.is_main and br.legacy_branch_id is null and nullif(p_legacy_branch_id, '') is not null then
    update cl_branches set legacy_branch_id = p_legacy_branch_id where id = br.id;
  end if;
  return cl_terminal_join_json(t.id, jc.id);   -- admin passcode from main
end $fn$;
grant execute on function public.cl_terminal_join(text, text, text, text, text, text, text, text, text, text, integer) to anon, authenticated;

-- 5. A main-branch till sets another till's Admin passcode -------------------
create function public.cl_terminal_admin_set(
  p_install_id text, p_secret_phrase text, p_device_key text, p_terminal_id uuid,
  p_admin_salt text, p_admin_check text, p_admin_rounds integer)
returns json
language plpgsql security definer set search_path = public as $fn$
declare v cl_vendors%rowtype; me cl_terminals%rowtype; t cl_terminals%rowtype;
begin
  v := cl_install_vendor(p_install_id, p_secret_phrase, p_device_key, false);
  select tt.* into me from cl_terminals tt join cl_branches b on b.id = tt.branch_id
   where tt.vendor_id = v.id and tt.active and b.is_main;
  if not found then raise exception 'Only a main-branch terminal can set a till''s Admin passcode' using errcode = 'P0001'; end if;
  if not cl_admin_seed_ok(p_admin_salt, p_admin_check, p_admin_rounds) then
    raise exception 'ADMIN_SEED_INVALID: That Admin passcode check value isn''t valid' using errcode = 'P0001';
  end if;
  select * into t from cl_terminals where id = p_terminal_id and business_id = me.business_id;
  if not found then raise exception 'Terminal not found in this business' using errcode = 'P0001'; end if;
  if t.id = me.id then raise exception 'A till sets its own Admin passcode in Settings' using errcode = 'P0001'; end if;
  insert into cl_terminal_admin_seeds (terminal_id, salt, check_value, rounds, set_by_terminal, created_ts, delivered_ts)
  values (t.id, p_admin_salt, p_admin_check, p_admin_rounds, me.id, now(), null)
  on conflict (terminal_id) do update set salt = excluded.salt, check_value = excluded.check_value, rounds = excluded.rounds,
    set_by_terminal = excluded.set_by_terminal, created_ts = excluded.created_ts, delivered_ts = null;
  insert into cl_activity_log (staff_id, action, target_table, target_id, detail)
  values (null, 'terminal_admin_set', 'cl_terminals', t.id,
          jsonb_build_object('till_code', t.till_code, 'branch_id', t.branch_id, 'by_terminal', me.id, 'by_till', me.till_code));
  return (cl_terminal_json(t.id)::jsonb || jsonb_build_object('admin_set', true))::json;
end $fn$;
grant execute on function public.cl_terminal_admin_set(text, text, text, uuid, text, text, integer) to anon, authenticated;

-- 6. Check-in (shared stock lock body + marked lines; same signature) ---------
create or replace function public.cl_device_checkin(
  p_install_id text, p_shop_secret_phrase text, p_device_code text, p_business_name text,
  p_owner_name text default null, p_phone text default null, p_city text default null,
  p_location text default null, p_rpn_hint_id uuid default null, p_device_key text default null,
  p_app_build integer default null)                                  -- build guard
returns json
language plpgsql security definer set search_path to 'public' as $function$
declare
  v_vendor cl_vendors%rowtype;
  v_messages json;
  v_terminal_id uuid;
  v_terminal_active boolean;                                         -- Phase 2
  v_branch_id uuid;                                                  -- shared stock lock
  v_app_build integer;                                               -- shared stock lock
  v_shared_lock boolean := false;                                    -- shared stock lock
  v_admin_seed json;                                                 -- admin passcode seed
  v_business_name text := nullif(trim(coalesce(p_business_name,'')), '');
  v_owner_name    text := nullif(trim(coalesce(p_owner_name,'')), '');
  v_phone         text := nullif(trim(coalesce(p_phone,'')), '');
  v_city          text := nullif(trim(coalesce(p_city,'')), '');
  v_location      text := nullif(trim(coalesce(p_location,'')), '');
  v_device_code   text := nullif(trim(coalesce(p_device_code,'')), '');
begin
  -- was: inline install/phrase checks + "insert if not found"
  v_vendor := cl_install_vendor(p_install_id, p_shop_secret_phrase, p_device_key, true, v_business_name, v_device_code);

  update cl_vendors set
    business_name       = coalesce(v_business_name, business_name),
    owner_name          = coalesce(v_owner_name, owner_name),
    phone               = coalesce(v_phone, phone),
    city                = coalesce(v_city, city),
    location            = coalesce(v_location, location),
    device_code         = coalesce(v_device_code, device_code),
    shop_secret_phrase  = coalesce(v_vendor.shop_secret_phrase, p_shop_secret_phrase),
    rpn_id              = coalesce(v_vendor.rpn_id, p_rpn_hint_id),
    last_checkin_at     = now()
  where id = v_vendor.id
  returning * into v_vendor;

  update cl_terminals set last_seen_ts = now(),
         app_build = case when p_app_build > 0 then p_app_build end, app_build_ts = now()   -- build guard
   where vendor_id = v_vendor.id
    returning id, active, branch_id, app_build                       -- shared stock lock: + branch_id, app_build
         into v_terminal_id, v_terminal_active, v_branch_id, v_app_build;   -- Phase 2: + active

  -- shared stock lock: a till at a shared-stock branch on a build before v7 must not sell
  if v_terminal_id is not null then
    v_shared_lock := coalesce((select stock_mode = 'shared' from cl_branches where id = v_branch_id), false)
                     and coalesce(v_app_build, 0) < 7;
  end if;

  -- admin passcode seed: a check value the main branch set for this till, delivered once
  if v_terminal_id is not null then
    update cl_terminal_admin_seeds set delivered_ts = now()
     where terminal_id = v_terminal_id and delivered_ts is null
    returning json_build_object('salt', salt, 'check', check_value, 'rounds', rounds, 'set_ts', created_ts) into v_admin_seed;
  end if;

  select coalesce(json_agg(json_build_object('id', id, 'title', title, 'body', body, 'created_at', created_at)), '[]'::json)
    into v_messages
    from cl_vendor_messages
    where vendor_id = v_vendor.id and channel = 'in_app' and status = 'pending';

  update cl_vendor_messages
    set status = 'delivered', delivered_at = now()
    where vendor_id = v_vendor.id and channel = 'in_app' and status = 'pending';

  return json_build_object(
    'vendor_id', v_vendor.id,
    'status', v_vendor.status,
    'lock_cart', case when v_shared_lock then true else v_vendor.lock_cart end,                 -- shared stock lock
    'lock_add_product', v_vendor.lock_add_product,
    'lock_reason', case when v_shared_lock and not coalesce(v_vendor.lock_cart, false)         -- shared stock lock
                        then 'This branch uses shared stock. Update the app before selling: tap Reload on the update banner, or reopen the app while online.'
                        else v_vendor.lock_reason end,
    'cycle_start_date', v_vendor.cycle_start_date,
    'messages', v_messages,
    'business_id', v_vendor.business_id,        -- Phase 1, additive
    'terminal_id', v_terminal_id,               -- Phase 1, additive
    'terminal_active', v_terminal_active,       -- Phase 2, additive
    'admin_seed', v_admin_seed                  -- admin passcode seed, additive
  );
end;
$function$;

commit;
